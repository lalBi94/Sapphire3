  let current = 'en'

  // Retourne un texte traduit, avec repli sur l'anglais puis sur la clef.
  function t(key, params = {}) {
    const text = dictionaries[current]?.[key] ?? dictionaries.en[key] ?? key
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match))
  }

  // Applique la langue courante au document et aux éléments annotés.
  function apply() {
    const root = document.documentElement
    root.lang = current
    root.dir = current === 'ar' ? 'rtl' : 'ltr'
    document.title = t('meta.title')
    const description = document.querySelector('meta[name="description"]')
    if (description) description.content = t('meta.description')
    for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n)
    for (const element of document.querySelectorAll('[data-i18n-html]')) element.innerHTML = t(element.dataset.i18nHtml)
    for (const element of document.querySelectorAll('[data-i18n-aria]')) element.setAttribute('aria-label', t(element.dataset.i18nAria))
    for (const element of document.querySelectorAll('[data-i18n-title]')) element.title = t(element.dataset.i18nTitle)
    for (const select of document.querySelectorAll('[data-site-language]')) select.value = current
  }

  // Change la langue, la mémorise et prévient les scripts de la page.
  function setLanguage(language, { persist = true } = {}) {
    current = languages.includes(language) ? language : 'en'
    if (persist) {
      try { localStorage.setItem(STORAGE_KEY, current) } catch { /* préférence indisponible : la page reste utilisable */ }
    }
    apply()
    document.dispatchEvent(new CustomEvent('site-language-change', { detail: { language: current } }))
  }

  // Retourne la langue active.
  function getLanguage() {
    return current
  }

  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (languages.includes(stored)) current = stored
  } catch { /* stockage local indisponible */ }

  for (const select of document.querySelectorAll('[data-site-language]')) {
    select.addEventListener('change', () => setLanguage(select.value))
  }

  apply()
  window.SiteI18n = { t, apply, setLanguage, getLanguage, languages }
