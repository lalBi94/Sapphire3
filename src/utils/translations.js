export const translations = {
  en: Object.fromEntries(Object.entries(messages).map(([key, texts]) => [key, texts[0]])),
  fr: Object.fromEntries(Object.entries(messages).map(([key, texts]) => [key, texts[1]])),
}

// Interpole seulement les paramètres affichés ; les données utilisateur ne deviennent jamais du HTML.
export function translate(language, key, values = {}) {
  const catalog = Object.hasOwn(translations, language) ? translations[language] : translations.en
  const text = Object.hasOwn(catalog, key) ? catalog[key] : Object.hasOwn(translations.en, key) ? translations.en[key] : String(key)
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => Object.hasOwn(values ?? {}, name) ? String(values[name]) : placeholder)
}

// Traduit un code stable sans dépendre des messages internes du moteur ou de Windows.
export function failureLabel(failure, t) {
  const code = failure?.code
  if (typeof code !== 'string') return t('errors.default')
  return Object.hasOwn(translations.en, `error.${code}`)
    ? t(`error.${code}`, failure.values)
    : t('errors.unknownCode', { code })
}
